#!/usr/bin/env node
/*
 * Writes dist/web/browser/assets/config.js after a production build.
 *
 * The bundle is environment-agnostic by design: assets/config.js is a plain
 * script that runs before it, sets window.__SPMS_CONFIG__, and wins over the
 * compiled defaults (see src/environments/runtime-config.ts). That is what lets
 * one built artifact be promoted between environments unrebuilt.
 *
 * This script exists so a host that has no post-build upload step — Vercel,
 * Netlify, Cloudflare Pages — can still produce that file from environment
 * variables set in its dashboard, rather than needing a code change to repoint
 * the site.
 *
 *   SPMS_USE_REAL_API   "true" to call a real API. Default false: demo mode.
 *   SPMS_API_BASE_URL   Absolute https origin, or same-origin path. No trailing
 *                       slash needed — runtime-config.ts strips it.
 *   SPMS_TENANT / SPMS_PROPERTY / SPMS_ACTOR
 *                       Development identity headers. Inert against a real
 *                       API, which reads claims from a bearer token.
 *
 * The default is demo mode ON PURPOSE. A deployed page served over HTTPS cannot
 * call an http://127.0.0.1 API — the browser blocks it as mixed content — so a
 * build that defaulted to the real API would present as a board that silently
 * fails every request. Demo mode makes the whole site usable from the URL with
 * nothing running anywhere.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

const OUT = resolve(process.argv[2] ?? 'dist/web/browser', 'assets/config.js');

const useRealApi = process.env.SPMS_USE_REAL_API === 'true';
const apiBaseUrl = process.env.SPMS_API_BASE_URL?.trim();

// Refused rather than written: a real-API build with no origin would fall back
// to the compiled '/api', which on a static host is a 404 on every call. A
// deploy that cannot work should fail at build time, where someone is watching.
if (useRealApi && !apiBaseUrl) {
  console.error(
    'SPMS_USE_REAL_API is true but SPMS_API_BASE_URL is not set.\n' +
    'A static host has nothing at /api, so every request would 404. Set the ' +
    'API origin, or leave SPMS_USE_REAL_API unset to deploy in demo mode.');
  process.exit(1);
}

if (apiBaseUrl && !/^https:/.test(apiBaseUrl) && !apiBaseUrl.startsWith('/')) {
  console.error(
    `SPMS_API_BASE_URL is "${apiBaseUrl}".\n` +
    'A page served over HTTPS cannot call an http:// origin; the browser blocks ' +
    'it as mixed content. Use an https origin or a same-origin path.');
  process.exit(1);
}

const config = {
  useRealApi,
  ...(apiBaseUrl ? { apiBaseUrl } : {}),
  ...(process.env.SPMS_TENANT ? { tenant: process.env.SPMS_TENANT } : {}),
  ...(process.env.SPMS_PROPERTY ? { property: process.env.SPMS_PROPERTY } : {}),
  ...(process.env.SPMS_ACTOR ? { actor: process.env.SPMS_ACTOR } : {}),
};

const body = `/* Generated by tools/write-runtime-config.mjs at build time.
 * Not part of the bundle and never fingerprinted: overwrite this one file on
 * the host to repoint the site, no rebuild. See README.md (Deployment). */
window.__SPMS_CONFIG__ = ${JSON.stringify(config, null, 2)};
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body, 'utf8');

console.log(`wrote ${OUT}`);
console.log(`  useRealApi ${config.useRealApi}`);
console.log(`  apiBaseUrl ${config.apiBaseUrl ?? '(compiled default)'}`);
